"""
Experiment 4C: Function Word Head Output Alignment
Experiment 4C: Alignment analysis of function word outputs after passing through attention heads

Research Question:
After Layer 3 attention heads process function words (words without semantic content),
is the output vector direction consistent with the massive activation direction generated by this layer?

Key Difference:
- Experiment 4B: Analyzes right singular vectors of weight matrices (static)
- Experiment 4C: Analyzes actual head outputs after processing function words (dynamic)

Methodology:
1. Identify function words (the, a, and, of, to, in, etc.)
2. Capture Layer 3 attention head outputs after processing these words
3. Calculate cosine similarity between head output directions and massive activation directions
4. Find which heads produce outputs consistent with massive activations for function words
"""

